#nullable enable

namespace Fodinae.Core;

/// <summary>
/// Как мир ложится на пиксельную сетку экрана.
/// </summary>
/// <remarks>
/// Три способа справиться с дробным числом экранных пикселей на тексель, и
/// других не существует. Выбор между ними — вкусовой, поэтому он вынесен
/// игроку, а не зашит: каждый вариант чем-то платит, и какая плата
/// приемлема, решается глазами.
///
/// ПОДПИСИ НЕ ЛОКАЛИЗОВАНЫ НАМЕРЕННО. Режим заведён, чтобы сравнить три
/// варианта вживую и выбрать один, а игровые тексты пишет человек. Кнопка
/// показывает техническое имя режима; когда победитель определится,
/// настройка либо получит человеческие подписи, либо исчезнет вместе с
/// проигравшими вариантами.
///
/// Числа, из-за которых всё: клетка 32 текселя при 16 пикселях на юнит,
/// при высоте 1080 и обычном зуме на тексель приходится 4.821 пикселя.
/// Целым это отношение не бывает, а ближайшая выборка требует целого —
/// отсюда удвоенные и потерянные строки текселей, то есть муар.
/// </remarks>
public enum PixelSamplingMode
{
    /// <summary>
    /// Плавный зум, границы текселей сглажены.
    /// </summary>
    /// <remarks>
    /// Зум любой, муар снимается при выборке: внутри текселя она остаётся
    /// ближайшей, размывается только граница и ровно на ширину экранного
    /// пикселя. Платит лёгкой мягкостью на границах текселей.
    /// </remarks>
    SmoothFiltered = 0,

    /// <summary>
    /// Ступенчатый зум, ни одного размытого пикселя.
    /// </summary>
    /// <remarks>
    /// Размер камеры округляется так, что на тексель приходится целое
    /// число пикселей, камера встаёт в узел сетки. Картинка предельно
    /// резкая, муара нет вовсе. Платит зумом: при 1080 и пределах 5–30
    /// ступеней всего пять, плавного приближения не остаётся.
    /// </remarks>
    PixelPerfect = 1,

    /// <summary>
    /// Как было: плавный зум, ближайшая выборка без сглаживания.
    /// </summary>
    /// <remarks>
    /// Оставлено намеренно, чтобы было с чем сравнивать: без исходного
    /// варианта под рукой нельзя судить, стоит ли лечение болезни.
    /// </remarks>
    Raw = 2,
}

/// <summary>
/// Что именно делает каждый режим.
/// </summary>
/// <remarks>
/// Правила вынесены из камеры и менеджера экрана отдельным типом, чтобы их
/// можно было исполнить вне Unity и проверить таблицей. Повод конкретный: в
/// режиме сглаживания камера округляла позицию к пиксельной сетке, и это
/// давало мелкую тряску всей картины — слежение идёт через SmoothDamp, его
/// выход ползёт непрерывно, и около границы округления округлённая позиция
/// скачет между соседними узлами по обеим осям.
///
/// Отсюда же инвариант: округлять позицию имеет право только тот режим,
/// который округляет и зум. Порознь эти две меры не дополняют друг друга, а
/// ссорятся — сетка, к которой округляется позиция, при дробном зуме сама
/// не совпадает с сеткой текселей.
/// </remarks>
public static class PixelSamplingRules
{
    /// <summary>Округляет ли режим позицию камеры к пиксельной сетке.</summary>
    public static bool SnapsCameraPosition(PixelSamplingMode mode) =>
        mode == PixelSamplingMode.PixelPerfect;

    /// <summary>Округляет ли режим размер камеры до целых пикселей на тексель.</summary>
    public static bool QuantizesZoom(PixelSamplingMode mode) =>
        mode == PixelSamplingMode.PixelPerfect;

    /// <summary>Сглаживает ли режим границы текселей в шейдере.</summary>
    public static bool FiltersTexelEdges(PixelSamplingMode mode) =>
        mode == PixelSamplingMode.SmoothFiltered;
}
