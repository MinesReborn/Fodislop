#nullable enable

namespace Kern.Rendering.PostProcessing;

// Калибровочный узор дисплея. Числа совпадают с _CalibrationPattern в
// PostProcess.compute и менять их в отрыве от шейдера нельзя.
public enum CalibrationPattern
{
    Off = 0,

    // Одно белое поле ровно в paper white: белая точка сверяется с бумагой
    // при том освещении, в котором человек играет.
    PaperWhite = 1,

    // Знак Kern на поле ярче любого дисплея (как HGIG): знак — выбранный пик; там, где он едва заметен,
    // и есть пик дисплея.
    PeakMark = 2,

    // Три знака чуть светлее чёрного: «не виден», «едва заметен», «виден». Уровень чёрного (HDR) или
    // яркость (SDR) подбираются, пока знаки не станут такими, как подписано.
    BlackMarks = 3,
}
