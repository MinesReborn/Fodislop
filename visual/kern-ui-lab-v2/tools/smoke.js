// Дымовой прогон v2: вызывается внутри макета обвязкой snap.html, итог пишет в title родителя.
(function () {
  const log = []; const errs = [];
  window.addEventListener('error', e => errs.push(e.message));
  const step = (name, fn, check) => { try { fn(); const r = check ? check() : true; log.push((r ? 'ok ' : 'FAIL ') + name); } catch (e) { errs.push(name + ': ' + e.message); } };
  const $ = id => document.getElementById(id);
  const key = (k) => document.body.dispatchEvent(new KeyboardEvent('keydown', { key: k, bubbles: true, cancelable: true }));
  step('ingame', () => switchViewState('ingame'), () => $('ingameView').classList.contains('active'));
  const before = $('basketMiniGrid').textContent;
  step('dig x40', () => { for (let i = 0; i < 40; i++) mockTouchDig(); }, () => $('hudMiniSkills').children.length >= 1);
  step('crystals grow', () => {}, () => $('basketMiniGrid').textContent !== before);
  step('autodig on/off', () => { toggleAutoDig(); toggleAutoDig(); }, () => !$('btnAutoDig').classList.contains('active'));
  step('hp damage/heal', () => simulateDamageOrHeal(), () => /HP$/.test($('hpText').textContent));
  step('bonus', () => claimBonus(), () => /^\$/.test($('hudMoney').textContent));
  step('chat mode 1', () => cycleChatMode(), () => $('gameHud').dataset.chat === '1');
  step('chat send', () => { $('chatColumnInput').value = 'проверка'; sendColumnChat(); }, () => $('chatColumnLines').textContent.includes('проверка'));
  step('chat list', () => setChatPanel('list'), () => !$('chatChannelList').hidden && $('chatTitle').textContent === 'СПИСОК ЧАТОВ');
  step('chat DNO', () => selectChatChannel('DNO'), () => $('chatTitle').textContent.startsWith('DNO'));
  step('chat mode 2', () => cycleChatMode(), () => $('gameHud').dataset.chat === '2');
  step('chat mode 0', () => cycleChatMode(), () => $('gameHud').dataset.chat === '0');
  step('enter opens chat', () => key('Enter'), () => $('gameHud').dataset.chat === '1');
  step('chat close', () => { cycleChatMode(); cycleChatMode(); }, () => $('gameHud').dataset.chat === '0');
  step('skills none', () => openSkillsWindow(-1), () => getOpenModal()?.id === 'skillsModal' && $('skillsPanel').textContent.includes('Купить слот'));
  step('skills select M', () => openSkillsWindow(2), () => $('skillsPanel').textContent.includes('Передвижение Уровень:12'));
  step('skills upgrade', () => upgradeSkill('M', 2), () => $('skillsPanel').textContent.includes('Уровень:13'));
  step('skills empty', () => openSkillsWindow(7), () => $('skillsPanel').querySelectorAll('.g-install-item').length === 18);
  step('close skills', () => closeModal('skillsModal'), () => !getOpenModal());
  step('respawn', () => { openModal('respawnModal'); doRespawn(); }, () => !getOpenModal());
  step('prog run', () => toggleHudProgram(), () => $('hudOnlineProg').textContent === '7');
  step('busy on', () => toggleHudBusy(), () => $('gameHud').classList.contains('is-busy') && !$('hudGeology').hidden);
  step('busy off', () => toggleHudBusy(), () => !$('gameHud').classList.contains('is-busy'));
  step('hotbar 3', () => selectHotbarSlot(2), () => document.querySelectorAll('#hotbarSlotsWrap .hotbar-slot')[2].classList.contains('active'));
  step('inventory expand', () => toggleMockInventory(), () => $('hotbarSlotsWrap').classList.contains('is-expanded'));
  step('tab inventory', () => key('Tab'), () => getOpenModal()?.id === 'inventoryModal');
  step('esc close', () => key('Escape'), () => !getOpenModal());
  step('esc pause', () => key('Escape'), () => currentMode === 'pause');
  step('resume', () => resumeGameFromPause(), () => currentMode === 'ingame');
  step('touch on', () => toggleTouchLayout(true), () => document.body.classList.contains('is-touch'));
  step('touch off', () => toggleTouchLayout(false), () => !document.body.classList.contains('is-touch'));
  for (const m of ['clanModal', 'traderModal', 'programmatorModal', 'chatModal', 'settingsModal', 'profileModal', 'chronicleModal', 'repairModal', 'serverBrowserModal'])
    step('modal ' + m, () => { openModal(m); closeModal(m); }, () => !getOpenModal());
  step('menu update shown', () => switchViewState('menu'), () => !$('btnUpdateRequired').hidden && $('btnStartDescent').hidden);
  step('update click opens modal', () => $('btnUpdateRequired').click(), () => getOpenModal()?.id === 'mandatoryUpdateModal');
  step('update toggle off', () => { closeModal('mandatoryUpdateModal'); toggleUpdateRequired(); }, () => $('btnUpdateRequired').hidden && !$('btnStartDescent').hidden);
  step('descent', () => handleDeployClick(), () => currentMode === 'descent');
  setTimeout(() => { parent.document.title = (errs.length ? 'ERRORS: ' + errs.join(' ; ') + ' || ' : 'NOERR || ') + log.join(', '); }, 50);
})();
